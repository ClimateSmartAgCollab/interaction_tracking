"""Data models for validation and review results."""

from dataclasses import dataclass, field
from typing import Any


@dataclass
class ReviewItem:
    """A single item requiring user review."""

    title: str
    category: str
    priority: str
    table_name: str
    record_id: Any
    excel_row: int
    field_name: str | None = None
    current_value: Any = None
    message: str = ""
    suggested_action: str | None = None


@dataclass
class Recommendation:
    """A suggested researcher status change."""

    recommendation_type: str
    researcher_id: Any
    reason: str
    current_status: str | None = None
    suggested_status: str | None = None


@dataclass
class ValidationResults:
    """Results generated by workbook validation."""

    structural: list[ReviewItem] = field(default_factory=list)
    researchers: list[ReviewItem] = field(default_factory=list)
    interactions: list[ReviewItem] = field(default_factory=list)
    contributions: list[ReviewItem] = field(default_factory=list)
    recommendations: list[Recommendation] = field(default_factory=list)
    completeness_metrics: dict[str, dict[str, float]] = field(
        default_factory=dict
    )